// Minimum age to use Emect. 18 keeps the app clear of India's DPDP Act rule that
// children under 18 need verified parental consent. Change it here only after
// legal advice. The date of birth is checked once and NEVER stored.
export const MIN_AGE = 18;

export function ageFromDob(dob: string, now = new Date()): number | null {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(dob)) return null;
  const [y, m, d] = dob.split("-").map(Number);
  const date = new Date(Date.UTC(y, m - 1, d));
  if (date.getUTCFullYear() !== y || date.getUTCMonth() !== m - 1 || date.getUTCDate() !== d) return null;
  let age = now.getUTCFullYear() - y;
  if (now.getUTCMonth() + 1 < m || (now.getUTCMonth() + 1 === m && now.getUTCDate() < d)) age--;
  return age >= 0 && age < 130 ? age : null;
}
